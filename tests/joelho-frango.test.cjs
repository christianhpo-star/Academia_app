const test=require('node:test');
const assert=require('node:assert/strict');
const N=require('../nutrition.js');
const CAT=require('../nutrition-catalog.js');
const FOOD='recipe:joelho-frango-assado-2026';
let seq=0;
const next=prefix=>prefix+'-'+(++seq);
const entry=item=>({id:next('meal'),date:'2026-11-16',mealType:'snack',time:null,notes:'',items:[item]});
test('joelho de frango is searchable as a separate estimated snack, not TACO or an exact label',()=>{
  const food=CAT.find(FOOD);
  assert.ok(food);
  assert.equal(food.category,'Salgados e lanches');
  assert.equal(food.estimate.confidence,'low');
  assert.equal(food.estimateGramsBase,100);
  assert.equal(food.nutrientsPer100g.energyKcal,null);
  assert.ok(CAT.search('joelho de frango').some(f=>f.id===FOOD));
  assert.ok(CAT.search('italiano de frango').some(f=>f.id===FOOD));
  assert.ok(CAT.orderedForMeal('snack').slice(0,5).some(f=>f.id===FOOD));
});
test('180 g photographed reference is approximately 540 kcal and shows uncertainty',()=>{
  const item=CAT.makeItem(FOOD,'one',1,next);
  assert.ok(item);
  assert.ok(N.validEntry(entry(item)));
  assert.equal(item.grams,180);
  assert.equal(item.quantity,1);
  assert.equal(item.estimate.central.energyKcal,540);
  assert.equal(item.estimate.low.energyKcal,468);
  assert.equal(item.estimate.high.energyKcal,630);
  assert.equal(item.estimate.central.proteinG,30.6);
  assert.equal(item.estimate.central.carbsG,59.4);
  assert.equal(item.estimate.central.fatG,19.8);
  const e=entry(item);
  assert.equal(N.observedTotals([e],e.date).totals.energyKcal,null);
  const t=N.estimatedTotals([e],e.date);
  assert.equal(t.estimatedItems,1);
  assert.equal(t.totals.central.energyKcal,540);
});
test('custom gram weight scales all estimates and does not fabricate exact nutrients',()=>{
  const twoHundred=CAT.makeItem(FOOD,'custom',200,next);
  assert.ok(twoHundred);
  assert.equal(twoHundred.grams,200);
  assert.equal(twoHundred.estimate.central.energyKcal,3);
  const e=entry(twoHundred);
  const t=N.estimatedTotals([e],e.date);
  assert.equal(t.totals.central.energyKcal,600);
  assert.equal(t.totals.low.energyKcal,520);
  assert.equal(t.totals.high.energyKcal,700);
  assert.equal(N.observedTotals([e],e.date).totals.energyKcal,null);
});
test('catalog lookup neither logs the food nor mutates past meals, weights, workouts',()=>{
  const snapshot={...N.archive(),entries:[]};
  const unchanged=JSON.stringify(snapshot);
  const item=CAT.makeItem(FOOD,'one',1,next);
  const archive=N.archive();
  assert.ok(N.validArchive(archive));
  assert.equal(JSON.stringify(snapshot),unchanged);
  assert.equal(archive.entries.length,0);
  assert.ok(item.estimate);
});
